alter table public.inventory_movements enable row level security;
alter table public.work_order_expenses enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists "Usuarios autenticados leen perfiles" on public.profiles;
drop policy if exists "Usuario actualiza su perfil" on public.profiles;
drop policy if exists "Usuarios autenticados gestionan productos" on public.products;
drop policy if exists "Usuarios autenticados gestionan OT" on public.work_orders;
drop policy if exists "Usuarios autenticados gestionan clientes" on public.clients;
drop policy if exists "Usuarios autenticados gestionan proveedores" on public.suppliers;
drop policy if exists "Usuarios autenticados gestionan movimientos" on public.inventory_movements;
drop policy if exists "Usuarios autenticados gestionan gastos" on public.work_order_expenses;
drop policy if exists "Usuarios autenticados leen auditoría" on public.audit_logs;
drop policy if exists "Usuarios autenticados crean auditoría" on public.audit_logs;

create policy "Usuarios autenticados leen perfiles" on public.profiles for select to authenticated using (true);
create policy "Usuario actualiza su perfil" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "Usuarios autenticados gestionan productos" on public.products for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados gestionan OT" on public.work_orders for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados gestionan clientes" on public.clients for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados gestionan proveedores" on public.suppliers for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados gestionan movimientos" on public.inventory_movements for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados gestionan gastos" on public.work_order_expenses for all to authenticated using (true) with check (true);
create policy "Usuarios autenticados leen auditoría" on public.audit_logs for select to authenticated using (true);
create policy "Usuarios autenticados crean auditoría" on public.audit_logs for insert to authenticated with check (auth.uid() = user_id);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles, public.products, public.work_orders, public.clients, public.suppliers,
  public.inventory_movements, public.work_order_expenses, public.audit_logs to authenticated;
grant usage, select on all sequences in schema public to authenticated;
